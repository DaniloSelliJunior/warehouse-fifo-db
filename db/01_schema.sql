-- =====================================================================
-- 01_schema.sql - Estrutura do banco (DDL) - PostgreSQL 16
-- Enderecamento e controle de estoque com saida FIFO + validade
-- Area de armazenagem e expedicao de uma loja de material de construcao
--
-- Executado automaticamente pelo Docker (docker-entrypoint-initdb.d)
-- ou manualmente: psql -d bd_deposito -f db/01_schema.sql
--
-- Convencoes (Elmasri & Navathe, 7a ed.): RELACOES em maiusculas,
-- atributos com a inicial maiuscula e restricoes nomeadas.
-- Obs.: sem aspas, o PostgreSQL guarda os nomes em minusculas;
-- as consultas funcionam com qualquer caixa.
-- =====================================================================

SET client_min_messages TO warning;
DROP SCHEMA IF EXISTS estoque CASCADE;
CREATE SCHEMA estoque;
SET search_path TO estoque, public;

-- Toda nova conexao ao banco ja enxerga o schema estoque
DO $$
BEGIN
    EXECUTE format('ALTER DATABASE %I SET search_path TO estoque, public', current_database());
END $$;

-- =====================================================================
-- PASSO 1 - Entidades regulares (PK substituta + chaves alternativas UNIQUE)
-- PASSO 4 - Relacionamentos 1:N viram FK no lado N (NOT NULL = participacao total)
-- =====================================================================

CREATE TABLE CATEGORIA (
    Id_categoria        INT GENERATED BY DEFAULT AS IDENTITY,
    Nome_categoria      VARCHAR(60)  NOT NULL,
    Descricao_categoria VARCHAR(200),
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (Id_categoria),
    CONSTRAINT UQ_CATEGORIA_NOME UNIQUE (Nome_categoria)
);

CREATE TABLE PRODUTO (
    Id_produto          INT GENERATED BY DEFAULT AS IDENTITY,
    Sku                 VARCHAR(20)  NOT NULL,
    Descricao           VARCHAR(120) NOT NULL,
    Unidade             VARCHAR(5)   NOT NULL,
    Peso_kg             DECIMAL(8,2),
    Perecivel           CHAR(1)      NOT NULL,
    Prazo_validade_dias INT,
    Id_categoria        INT          NOT NULL,          -- PERTENCE (N:1, total)
    CONSTRAINT PK_PRODUTO PRIMARY KEY (Id_produto),
    CONSTRAINT UQ_PRODUTO_SKU UNIQUE (Sku),
    CONSTRAINT FK_PRODUTO_CATEGORIA FOREIGN KEY (Id_categoria)
        REFERENCES CATEGORIA (Id_categoria),
    CONSTRAINT CK_PRODUTO_PERECIVEL CHECK (Perecivel IN ('S','N')),
    CONSTRAINT CK_PRODUTO_VALIDADE CHECK (
        (Perecivel = 'S' AND Prazo_validade_dias IS NOT NULL AND Prazo_validade_dias > 0) OR
        (Perecivel = 'N' AND Prazo_validade_dias IS NULL))
);

CREATE TABLE FORNECEDOR (
    Id_fornecedor INT GENERATED BY DEFAULT AS IDENTITY,
    Razao_social  VARCHAR(100) NOT NULL,
    Cnpj          VARCHAR(18)  NOT NULL,
    Telefone      VARCHAR(15),
    Cidade        VARCHAR(60),
    CONSTRAINT PK_FORNECEDOR PRIMARY KEY (Id_fornecedor),
    CONSTRAINT UQ_FORNECEDOR_CNPJ UNIQUE (Cnpj)
);

CREATE TABLE FUNCIONARIO (
    Id_funcionario   INT GENERATED BY DEFAULT AS IDENTITY,
    Nome_funcionario VARCHAR(80) NOT NULL,
    Matricula        VARCHAR(10) NOT NULL,
    Cargo            VARCHAR(40) NOT NULL,
    CONSTRAINT PK_FUNCIONARIO PRIMARY KEY (Id_funcionario),
    CONSTRAINT UQ_FUNCIONARIO_MATRICULA UNIQUE (Matricula)
);

CREATE TABLE CLIENTE (
    Id_cliente       INT GENERATED BY DEFAULT AS IDENTITY,
    Nome_cliente     VARCHAR(100) NOT NULL,
    Cpf_cnpj         VARCHAR(18)  NOT NULL,
    Telefone_cliente VARCHAR(15),
    Cidade_cliente   VARCHAR(60),
    CONSTRAINT PK_CLIENTE PRIMARY KEY (Id_cliente),
    CONSTRAINT UQ_CLIENTE_CPF_CNPJ UNIQUE (Cpf_cnpj)
);

CREATE TABLE ZONA (
    Id_zona      INT GENERATED BY DEFAULT AS IDENTITY,
    Nome_zona    VARCHAR(70) NOT NULL,
    Local_fisico VARCHAR(10) NOT NULL,
    Funcao       VARCHAR(10) NOT NULL,
    CONSTRAINT PK_ZONA PRIMARY KEY (Id_zona),
    CONSTRAINT UQ_ZONA_NOME UNIQUE (Nome_zona),
    CONSTRAINT CK_ZONA_LOCAL CHECK (Local_fisico IN ('ESTOQUE','MEZANINO','EXPEDICAO')),
    CONSTRAINT CK_ZONA_FUNCAO CHECK (Funcao IN ('PICKING','RESERVA'))
);

-- PASSO 5 - ACEITA (M:N) -> tabela propria com PK composta
CREATE TABLE ZONA_CATEGORIA (
    Id_zona      INT NOT NULL,
    Id_categoria INT NOT NULL,
    CONSTRAINT PK_ZONA_CATEGORIA PRIMARY KEY (Id_zona, Id_categoria),
    CONSTRAINT FK_ZC_ZONA FOREIGN KEY (Id_zona) REFERENCES ZONA (Id_zona),
    CONSTRAINT FK_ZC_CATEGORIA FOREIGN KEY (Id_categoria) REFERENCES CATEGORIA (Id_categoria)
);

-- PASSO 8A - Superclasse ENDERECO (especializacao total e disjunta)
CREATE TABLE ENDERECO (
    Id_endereco     INT GENERATED BY DEFAULT AS IDENTITY,
    Id_zona         INT         NOT NULL,          -- CONTEM (N:1, total)
    Codigo_endereco VARCHAR(20) NOT NULL,
    Corredor        CHAR(1)     NOT NULL,
    Modulo          INT         NOT NULL,
    Nivel           INT         NOT NULL,
    Capacidade_max  INT         NOT NULL,
    Tipo_endereco   CHAR(2)     NOT NULL,          -- atributo definidor
    Ativo           CHAR(1)     NOT NULL DEFAULT 'S',
    CONSTRAINT PK_ENDERECO PRIMARY KEY (Id_endereco),
    CONSTRAINT UQ_ENDERECO_CODIGO UNIQUE (Codigo_endereco),
    CONSTRAINT FK_ENDERECO_ZONA FOREIGN KEY (Id_zona) REFERENCES ZONA (Id_zona),
    CONSTRAINT CK_ENDERECO_MODULO CHECK (Modulo > 0),
    CONSTRAINT CK_ENDERECO_NIVEL CHECK (Nivel >= 0),
    CONSTRAINT CK_ENDERECO_CAPACIDADE CHECK (Capacidade_max > 0),
    CONSTRAINT CK_ENDERECO_TIPO CHECK (Tipo_endereco IN ('PP','PR','PI')),
    CONSTRAINT CK_ENDERECO_ATIVO CHECK (Ativo IN ('S','N'))
);

-- PASSO 8A - Subclasses: PK = FK para a superclasse
CREATE TABLE ENDERECO_PORTA_PALLET (
    Id_endereco  INT          NOT NULL,
    Altura_vao_m DECIMAL(4,2) NOT NULL,
    Carga_max_kg INT          NOT NULL,
    CONSTRAINT PK_END_PORTA_PALLET PRIMARY KEY (Id_endereco),
    CONSTRAINT FK_END_PORTA_PALLET FOREIGN KEY (Id_endereco)
        REFERENCES ENDERECO (Id_endereco) ON DELETE CASCADE
);

CREATE TABLE ENDERECO_PRATELEIRA (
    Id_endereco    INT          NOT NULL,
    Largura_m      DECIMAL(4,2) NOT NULL,
    Carga_nivel_kg INT          NOT NULL,
    CONSTRAINT PK_END_PRATELEIRA PRIMARY KEY (Id_endereco),
    CONSTRAINT FK_END_PRATELEIRA FOREIGN KEY (Id_endereco)
        REFERENCES ENDERECO (Id_endereco) ON DELETE CASCADE
);

CREATE TABLE ENDERECO_PISO (
    Id_endereco      INT          NOT NULL,
    Area_m2          DECIMAL(6,2) NOT NULL,
    Empilhamento_max INT          NOT NULL,
    CONSTRAINT PK_END_PISO PRIMARY KEY (Id_endereco),
    CONSTRAINT FK_END_PISO FOREIGN KEY (Id_endereco)
        REFERENCES ENDERECO (Id_endereco) ON DELETE CASCADE
);

CREATE TABLE RECEBIMENTO (
    Id_recebimento   INT GENERATED BY DEFAULT AS IDENTITY,
    Numero_nf        VARCHAR(15) NOT NULL,
    Data_recebimento DATE        NOT NULL,
    Id_fornecedor    INT         NOT NULL,          -- FORNECE (N:1, total)
    Id_funcionario   INT         NOT NULL,          -- CONFERE (N:1, total)
    CONSTRAINT PK_RECEBIMENTO PRIMARY KEY (Id_recebimento),
    CONSTRAINT UQ_RECEBIMENTO_NF UNIQUE (Numero_nf, Id_fornecedor),
    CONSTRAINT FK_RECEB_FORNECEDOR FOREIGN KEY (Id_fornecedor)
        REFERENCES FORNECEDOR (Id_fornecedor),
    CONSTRAINT FK_RECEB_FUNCIONARIO FOREIGN KEY (Id_funcionario)
        REFERENCES FUNCIONARIO (Id_funcionario)
);

CREATE TABLE LOTE (
    Id_lote             INT GENERATED BY DEFAULT AS IDENTITY,
    Id_produto          INT         NOT NULL,          -- POSSUI (N:1, total)
    Id_recebimento      INT         NOT NULL,          -- TRAZ   (N:1, total)
    Codigo_lote         VARCHAR(20) NOT NULL,
    Data_fabricacao     DATE,
    Data_validade       DATE,                  -- NULL = produto sem validade
    Quantidade_recebida INT         NOT NULL,
    CONSTRAINT PK_LOTE PRIMARY KEY (Id_lote),
    CONSTRAINT UQ_LOTE_PRODUTO_CODIGO UNIQUE (Id_produto, Codigo_lote),
    CONSTRAINT FK_LOTE_PRODUTO FOREIGN KEY (Id_produto) REFERENCES PRODUTO (Id_produto),
    CONSTRAINT FK_LOTE_RECEBIMENTO FOREIGN KEY (Id_recebimento)
        REFERENCES RECEBIMENTO (Id_recebimento),
    CONSTRAINT CK_LOTE_QUANTIDADE CHECK (Quantidade_recebida > 0),
    CONSTRAINT CK_LOTE_DATAS CHECK (Data_validade IS NULL OR Data_fabricacao IS NULL
                                    OR Data_validade >= Data_fabricacao)
);

-- PASSO 5 - ARMAZENA (M:N com atributo quantidade) -> saldo por endereco
CREATE TABLE ESTOQUE_ENDERECO (
    Id_lote     INT NOT NULL,
    Id_endereco INT NOT NULL,
    Quantidade  INT NOT NULL,
    CONSTRAINT PK_ESTOQUE_ENDERECO PRIMARY KEY (Id_lote, Id_endereco),
    CONSTRAINT FK_EE_LOTE FOREIGN KEY (Id_lote) REFERENCES LOTE (Id_lote),
    CONSTRAINT FK_EE_ENDERECO FOREIGN KEY (Id_endereco) REFERENCES ENDERECO (Id_endereco),
    CONSTRAINT CK_EE_QUANTIDADE CHECK (Quantidade >= 0)
);

CREATE TABLE VENDA (
    Id_venda       INT GENERATED BY DEFAULT AS IDENTITY,
    Data_venda     DATE NOT NULL,
    Id_cliente     INT  NOT NULL,          -- COMPRA (N:1, total)
    Id_funcionario INT  NOT NULL,          -- VENDE  (N:1, total)
    CONSTRAINT PK_VENDA PRIMARY KEY (Id_venda),
    CONSTRAINT FK_VENDA_CLIENTE FOREIGN KEY (Id_cliente) REFERENCES CLIENTE (Id_cliente),
    CONSTRAINT FK_VENDA_FUNCIONARIO FOREIGN KEY (Id_funcionario)
        REFERENCES FUNCIONARIO (Id_funcionario)
);

CREATE TABLE ITEM_VENDA (
    Id_item_venda   INT GENERATED BY DEFAULT AS IDENTITY,
    Id_venda        INT           NOT NULL,          -- COMPOE (N:1, total)
    Id_produto      INT           NOT NULL,          -- REFERE (N:1, total)
    Quantidade_item INT           NOT NULL,
    Preco_unitario  DECIMAL(10,2) NOT NULL,
    CONSTRAINT PK_ITEM_VENDA PRIMARY KEY (Id_item_venda),
    CONSTRAINT UQ_ITEM_VENDA_PRODUTO UNIQUE (Id_venda, Id_produto),   -- um produto por venda
    CONSTRAINT FK_ITEM_VENDA FOREIGN KEY (Id_venda) REFERENCES VENDA (Id_venda),
    CONSTRAINT FK_ITEM_PRODUTO FOREIGN KEY (Id_produto) REFERENCES PRODUTO (Id_produto),
    CONSTRAINT CK_ITEM_QUANTIDADE CHECK (Quantidade_item > 0),
    CONSTRAINT CK_ITEM_PRECO CHECK (Preco_unitario >= 0)
);

-- PASSO 8A - Superclasse MOVIMENTACAO (generalizacao total e disjunta)
CREATE TABLE MOVIMENTACAO (
    Id_movimentacao INT GENERATED BY DEFAULT AS IDENTITY,
    Tipo_mov        CHAR(1)   NOT NULL,          -- atributo definidor
    Data_hora       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Quantidade_mov  INT       NOT NULL,
    Id_lote         INT       NOT NULL,          -- MOV_LOTE     (N:1, total)
    Id_endereco     INT       NOT NULL,          -- MOV_ENDERECO (N:1, total)
    Id_funcionario  INT       NOT NULL,          -- REGISTRA     (N:1, total)
    CONSTRAINT PK_MOVIMENTACAO PRIMARY KEY (Id_movimentacao),
    CONSTRAINT FK_MOV_LOTE FOREIGN KEY (Id_lote) REFERENCES LOTE (Id_lote),
    CONSTRAINT FK_MOV_ENDERECO FOREIGN KEY (Id_endereco) REFERENCES ENDERECO (Id_endereco),
    CONSTRAINT FK_MOV_FUNCIONARIO FOREIGN KEY (Id_funcionario)
        REFERENCES FUNCIONARIO (Id_funcionario),
    CONSTRAINT CK_MOV_TIPO CHECK (Tipo_mov IN ('E','S')),
    CONSTRAINT CK_MOV_QUANTIDADE CHECK (Quantidade_mov > 0)
);

-- PASSO 8A - Subclasse ENTRADA: SUGERE (1:N, participacao PARCIAL -> FK aceita NULL)
CREATE TABLE ENTRADA_ESTOQUE (
    Id_movimentacao      INT NOT NULL,
    Id_endereco_sugerido INT,
    CONSTRAINT PK_ENTRADA_ESTOQUE PRIMARY KEY (Id_movimentacao),
    CONSTRAINT FK_ENTRADA_MOV FOREIGN KEY (Id_movimentacao)
        REFERENCES MOVIMENTACAO (Id_movimentacao) ON DELETE CASCADE,
    CONSTRAINT FK_ENTRADA_SUGERIDO FOREIGN KEY (Id_endereco_sugerido)
        REFERENCES ENDERECO (Id_endereco)
);

-- PASSO 8A - Subclasse SAIDA: ATENDE (1:N, participacao TOTAL -> FK NOT NULL)
CREATE TABLE SAIDA_ESTOQUE (
    Id_movimentacao INT NOT NULL,
    Id_item_venda   INT NOT NULL,
    CONSTRAINT PK_SAIDA_ESTOQUE PRIMARY KEY (Id_movimentacao),
    CONSTRAINT FK_SAIDA_MOV FOREIGN KEY (Id_movimentacao)
        REFERENCES MOVIMENTACAO (Id_movimentacao) ON DELETE CASCADE,
    CONSTRAINT FK_SAIDA_ITEM FOREIGN KEY (Id_item_venda)
        REFERENCES ITEM_VENDA (Id_item_venda)
);

-- ---------- Indices nas FKs mais consultadas (PostgreSQL nao cria automaticamente) ----------
CREATE INDEX IX_PRODUTO_CATEGORIA   ON PRODUTO (Id_categoria);
CREATE INDEX IX_ENDERECO_ZONA       ON ENDERECO (Id_zona);
CREATE INDEX IX_LOTE_PRODUTO_VALID  ON LOTE (Id_produto, Data_validade);   -- ordem FIFO/validade
CREATE INDEX IX_EE_ENDERECO         ON ESTOQUE_ENDERECO (Id_endereco);
CREATE INDEX IX_MOV_LOTE_ENDERECO   ON MOVIMENTACAO (Id_lote, Id_endereco);
CREATE INDEX IX_ITEM_VENDA_PRODUTO  ON ITEM_VENDA (Id_produto);

-- ---------- Documentacao no catalogo (dicionario de dados) ----------
COMMENT ON SCHEMA estoque IS 'Enderecamento e controle de estoque FIFO + validade';
COMMENT ON TABLE CATEGORIA             IS 'Agrupamento de produtos; define em quais zonas o produto pode ficar';
COMMENT ON TABLE PRODUTO               IS 'Item vendido pela loja; perecivel exige prazo de validade';
COMMENT ON TABLE FORNECEDOR            IS 'Empresa que entrega mercadoria (FORNECE recebimentos)';
COMMENT ON TABLE FUNCIONARIO           IS 'Quem confere, vende e registra movimentacoes';
COMMENT ON TABLE CLIENTE               IS 'Comprador pessoa fisica ou juridica';
COMMENT ON TABLE ZONA                  IS 'Area fisica do deposito (estoque, mezanino, expedicao) com funcao picking ou reserva';
COMMENT ON TABLE ENDERECO_PORTA_PALLET IS 'Subclasse PP de ENDERECO (opcao 8A)';
COMMENT ON TABLE ENDERECO_PRATELEIRA   IS 'Subclasse PR de ENDERECO (opcao 8A)';
COMMENT ON TABLE ENDERECO_PISO         IS 'Subclasse PI de ENDERECO (opcao 8A)';
COMMENT ON TABLE RECEBIMENTO           IS 'Nota fiscal de entrada conferida por um funcionario';
COMMENT ON TABLE LOTE                  IS 'Quantidade de um produto com mesma fabricacao e validade, vinda de um recebimento';
COMMENT ON TABLE VENDA                 IS 'Pedido de um cliente';
COMMENT ON TABLE ITEM_VENDA            IS 'Produto e quantidade de uma venda (um produto por venda)';
COMMENT ON TABLE ENTRADA_ESTOQUE       IS 'Subclasse E de MOVIMENTACAO: guarda o endereco sugerido (SUGERE)';
COMMENT ON TABLE SAIDA_ESTOQUE         IS 'Subclasse S de MOVIMENTACAO: liga a saida ao item vendido (ATENDE)';
COMMENT ON TABLE ENDERECO IS 'Superclasse da especializacao total e disjunta (8A): PP, PR ou PI';
COMMENT ON TABLE ESTOQUE_ENDERECO IS 'Relacionamento M:N ARMAZENA: saldo de cada lote em cada endereco';
COMMENT ON TABLE ZONA_CATEGORIA IS 'Relacionamento M:N ACEITA: categorias que cada zona pode guardar';
COMMENT ON TABLE MOVIMENTACAO IS 'Superclasse da generalizacao total e disjunta (8A): entrada ou saida';
COMMENT ON COLUMN ENTRADA_ESTOQUE.Id_endereco_sugerido IS 'SUGERE (1:N, participacao parcial): pode ser nulo';
COMMENT ON COLUMN LOTE.Data_validade IS 'Nula para produto nao perecivel';
